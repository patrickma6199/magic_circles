def shade(colour, factor):
    return tuple(max(0, min(255, round(c * factor))) for c in colour)


def lift(colour, amount):
    """Mixes toward white - chalk dust, not just a brighter colour."""
    return tuple(round(c + (255 - c) * amount) for c in colour)


def texture(base, seed):
    rng = random.Random(seed)
    image = Image.new("RGBA", (16, 16))
    px = image.load()

    # Faint lengthwise streaks, one value per column, so the sides read as a pressed stick.
    column_tone = [rng.uniform(0.93, 1.05) for _ in range(16)]

    def side_pixel(x):
        tone = column_tone[x] * rng.uniform(0.96, 1.04)
        colour = shade(base, tone)
        roll = rng.random()
        if roll < 0.07:
            colour = lift(colour, 0.25)       # a fleck of loose dust
        elif roll < 0.12:
            colour = shade(colour, 0.85)      # a pit in the surface
        return colour

    for y in range(16):
        for x in range(16):
            px[x, y] = (*side_pixel(x), 255)

    # Darker toward the bottom of the sides - where fingers hold it.
    for y in range(7, 10):
        for x in range(0, 4):
            r, g, b, _ = px[x, y]
            px[x, y] = (*shade((r, g, b), 0.94 - (y - 7) * 0.02), 255)

    # Broken bottom end: darker and rough.
    for y in range(0, 4):
        for x in range(4, 8):
            px[x, y] = (*shade(base, rng.uniform(0.78, 0.9)), 255)

    # Shoulder around the tip: dusty.
    for y in range(4, 8):
        for x in range(4, 8):
            px[x, y] = (*lift(shade(base, rng.uniform(0.98, 1.04)), 0.18), 255)

    # Worn tip face: rubbed smooth and pale from drawing.
    for y in range(0, 3):
        for x in range(8, 11):
            px[x, y] = (*lift(base, rng.uniform(0.32, 0.4)), 255)

    # Tip sides.
    for y in range(4, 6):
        for x in range(8, 11):
            px[x, y] = (*lift(shade(base, rng.uniform(0.97, 1.03)), 0.2), 255)

    return image


def main():
    for index, (name, base) in enumerate(CHALKS.items()):
        tex_path = ROOT / "textures/item" / f"{name}.png"
        texture(base, seed=9000 + index).save(tex_path)

        model = json.loads(json.dumps(MODEL))
        model["textures"]["chalk"] = f"magiccircles:item/{name}"
        model["textures"]["particle"] = f"magiccircles:item/{name}"
        model_path = ROOT / "models/item" / f"{name}.json"
        model_path.write_text(json.dumps(model, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {tex_path.name} and {model_path.name}")


if __name__ == "__main__":
    main()
