"""Generates the six chalk items as 3D sticks - a 16x16 texture and an element model for each:

  textures/item/<name>.png   - the chalk's surface, laid out in regions the model's faces sample
  models/item/<name>.json    - a 4x4 stick ten pixels long with a narrower, worn tip

Each chalk is coloured through and through in its own rune colour, not a white stick with a band.

Texture layout (pixels), matching the UVs in MODEL below:
  x 0-3,  y 0-9   the stick's four sides: the colour, faint lengthwise streaks and specks
  x 4-7,  y 0-3   the broken bottom end: a shade darker, rougher
  x 4-7,  y 4-7   the top shoulder around the tip: dusty, a shade lighter
  x 8-10, y 0-2   the worn tip's face: lightest - rubbed smooth from drawing
  x 8-10, y 4-5   the tip's sides: between the two
Everything else is filled with the side pattern so nothing samples a gap.
"""
